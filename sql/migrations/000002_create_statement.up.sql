DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'policy_effect') THEN
CREATE TYPE policy_effect AS ENUM ('ALLOW', 'DENY');
END IF;
END $$;

CREATE TABLE public.statement
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    policy_id  BIGINT      NOT NULL,
    sid        VARCHAR(100),
    effect     policy_effect NOT NULL,
    created_at TIMESTAMP   NOT NULL DEFAULT NOW(),

    CONSTRAINT statement_pk
        PRIMARY KEY (id),

    CONSTRAINT statement_policy_fk
        FOREIGN KEY (policy_id)
            REFERENCES public.policy (id)
            ON DELETE CASCADE
);

CREATE INDEX statement_policy_idx
    ON public.statement (policy_id);